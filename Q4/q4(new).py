def identity_preservation_score(
    person_path,
    output_path
):

    original = cv2.imread(
        person_path
    )

    generated = cv2.imread(
        output_path
    )

    if original is None:
        raise FileNotFoundError(
            person_path
        )

    if generated is None:
        raise FileNotFoundError(
            output_path
        )

    # Ensure spatial alignment
    if generated.shape[:2] != original.shape[:2]:

        generated = cv2.resize(
            generated,
            (
                original.shape[1],
                original.shape[0]
            ),
            interpolation=cv2.INTER_AREA
        )

    bbox = detect_original_face_bbox(
        person_path
    )

    if bbox is None:
        raise RuntimeError(
            f"Face not detected: {person_path}"
        )

    x1, y1, x2, y2 = bbox

    original_face = original[
        y1:y2,
        x1:x2
    ]

    generated_face = generated[
        y1:y2,
        x1:x2
    ]

    FACE_SIZE = (256, 256)

    original_face = cv2.resize(
        original_face,
        FACE_SIZE,
        interpolation=cv2.INTER_AREA
    )

    generated_face = cv2.resize(
        generated_face,
        FACE_SIZE,
        interpolation=cv2.INTER_AREA
    )

    original_gray = cv2.cvtColor(
        original_face,
        cv2.COLOR_BGR2GRAY
    )

    generated_gray = cv2.cvtColor(
        generated_face,
        cv2.COLOR_BGR2GRAY
    )

    score = ssim(
        original_gray,
        generated_gray,
        data_range=255
    )

    return float(score)



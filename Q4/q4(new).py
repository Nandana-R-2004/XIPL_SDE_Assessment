def detect_original_face_bbox(
    image_path,
    padding=0.20
):

    image = cv2.imread(
        image_path
    )

    if image is None:
        raise FileNotFoundError(
            image_path
        )

    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    faces = face_detector.detectMultiScale(
        gray,
        scaleFactor=1.1,
        minNeighbors=5,
        minSize=(50, 50)
    )

    if len(faces) == 0:
        return None

    x, y, w, h = max(
        faces,
        key=lambda box:
        box[2] * box[3]
    )

    pad_x = int(w * padding)
    pad_y = int(h * padding)

    x1 = max(
        0,
        x - pad_x
    )

    y1 = max(
        0,
        y - pad_y
    )

    x2 = min(
        image.shape[1],
        x + w + pad_x
    )

    y2 = min(
        image.shape[0],
        y + h + pad_y
    )

    return (
        int(x1),
        int(y1),
        int(x2),
        int(y2)
    )



def extract_face_region(
    image_path,
    padding=0.20
):
    """
    Detect the largest face in an image and return
    the padded RGB face crop.

    Returns:
        face_crop
        bbox = (x1, y1, x2, y2)

    If no face is detected:
        returns None, None
    """

    image = cv2.imread(image_path)

    if image is None:
        raise FileNotFoundError(
            f"Could not read image: {image_path}"
        )

    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    faces = face_detector.detectMultiScale(
        gray,
        scaleFactor=1.1,
        minNeighbors=5,
        minSize=(50, 50)
    )

    if len(faces) == 0:
        return None, None

    # Select largest detected face
    x, y, w, h = max(
        faces,
        key=lambda box: box[2] * box[3]
    )

    pad_x = int(w * padding)
    pad_y = int(h * padding)

    x1 = max(0, x - pad_x)
    y1 = max(0, y - pad_y)

    x2 = min(
        image.shape[1],
        x + w + pad_x
    )

    y2 = min(
        image.shape[0],
        y + h + pad_y
    )

    face = image[
        y1:y2,
        x1:x2
    ]

    face = cv2.cvtColor(
        face,
        cv2.COLOR_BGR2RGB
    )

    return face, (x1, y1, x2, y2)



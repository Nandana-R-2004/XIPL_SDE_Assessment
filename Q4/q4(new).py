def parse_judge_response(response):
    """
    Extract:
        score  -> integer 1-10
        reason -> string

    from MiniCPM's JSON response.
    """

    if not isinstance(response, str):
        response = str(response)

    text = response.strip()

    # Remove possible markdown fences
    text = text.replace("```json", "")
    text = text.replace("```", "")
    text = text.strip()

    # Try direct JSON first
    try:
        data = json.loads(text)

    except json.JSONDecodeError:

        # Extract first JSON object if model added extra text
        match = re.search(
            r'\{.*?\}',
            text,
            flags=re.DOTALL
        )

        if not match:
            raise ValueError(
                "Could not find JSON in VLM response:\n"
                + text
            )

        data = json.loads(
            match.group(0)
        )

    if "score" not in data:
        raise ValueError(
            f"VLM response missing 'score': {data}"
        )

    if "reason" not in data:
        raise ValueError(
            f"VLM response missing 'reason': {data}"
        )

    score = int(data["score"])
    reason = str(data["reason"]).strip()

    if not 1 <= score <= 10:
        raise ValueError(
            f"Invalid VLM score: {score}"
        )

    if not reason:
        raise ValueError(
            "VLM returned an empty reason."
        )

    return score, reason


def vlm_judge_pair(pair):
    """
    Evaluate one Q3 try-on result using the SAME Q1 MiniCPM-V model.

    Image order:
        1. Original person
        2. Target garment
        3. Q3 generated output
    """

    person = Image.open(
        pair["person_path"]
    ).convert("RGB")

    garment = Image.open(
        pair["garment_path"]
    ).convert("RGB")

    output = Image.open(
        pair["output_path"]
    ).convert("RGB")

    # MiniCPM multi-image conversation.
    # Each PIL image appears before the text rubric.
    msgs = [
        {
            "role": "user",
            "content": [
                person,
                garment,
                output,
                JUDGE_RUBRIC
            ]
        }
    ]

    response = vlm_model.chat(
        image=None,
        msgs=msgs,
        tokenizer=vlm_tokenizer,
        sampling=False,
        max_new_tokens=350
    )

    score, reason = parse_judge_response(
        response
    )

    return {
        "score": score,
        "reason": reason,
        "raw_response": str(response)
    }



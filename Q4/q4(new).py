def extract_garment_region(output_path, mask_path):

    output = Image.open(
        output_path
    ).convert("RGB")

    mask = Image.open(
        mask_path
    ).convert("L")

    if mask.size != output.size:
        mask = mask.resize(
            output.size,
            Image.Resampling.NEAREST
        )

    output_np = np.array(output)
    mask_np = np.array(mask) > 127

    if not np.any(mask_np):
        raise ValueError(
            f"Empty mask: {mask_path}"
        )

    ys, xs = np.where(mask_np)

    x1 = int(xs.min())
    x2 = int(xs.max())
    y1 = int(ys.min())
    y2 = int(ys.max())

    crop = output_np[
        y1:y2 + 1,
        x1:x2 + 1
    ]

    crop_mask = mask_np[
        y1:y2 + 1,
        x1:x2 + 1
    ]

    # White neutral background outside evaluated region
    neutral = np.full_like(
        crop,
        255
    )

    region = np.where(
        crop_mask[..., None],
        crop,
        neutral
    )

    return Image.fromarray(
        region.astype(np.uint8)
    )



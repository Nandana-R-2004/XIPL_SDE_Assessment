def identity_preservation_score(person_path, output_path):
    """
    Face-region SSIM.

    The face bbox is detected from the ORIGINAL person image
    and the same spatial region is extracted from both the
    original and generated image.

    This avoids inconsistent face detector boxes between
    original and output images.
    """

    original = cv2.imread(person_path)
    generated = cv2.imread(output_path)

    if original is None:
        raise FileNotFoundError(person_path)

    if generated is None:
        raise FileNotFoundError(output_path)

    # Generated Q3 outputs should correspond spatially to person
    if generated.shape[:2] != original.shape[:2]:
        generated = cv2.resize(
            generated,
            (original.shape[1], original.shape[0]),
            interpolation=cv2.INTER_AREA
        )

    # Detect face on ORIGINAL image
    _, bbox = extract_face_region(
        person_path,
        padding=0.20
    )

    if bbox is None:
        raise RuntimeError(
            f"Face not detected: {person_path}"
        )

    x1, y1, x2, y2 = [
        int(v) for v in bbox
    ]

    # Same spatial region from both images
    original_face = original[
        y1:y2,
        x1:x2
    ]

    generated_face = generated[
        y1:y2,
        x1:x2
    ]

    if original_face.size == 0 or generated_face.size == 0:
        raise RuntimeError(
            f"Invalid face crop for {person_path}"
        )

    # Standardize
    FACE_SIZE = (256, 256)

    original_face = cv2.resize(
        original_face,
        FACE_SIZE,
        interpolation=cv2.INTER_AREA
    )

    generated_face = cv2.resize(
        generated_face,
        FACE_SIZE,
        interpolation=cv2.INTER_AREA
    )

    # Grayscale SSIM
    original_gray = cv2.cvtColor(
        original_face,
        cv2.COLOR_BGR2GRAY
    )

    generated_gray = cv2.cvtColor(
        generated_face,
        cv2.COLOR_BGR2GRAY
    )

    score = ssim(
        original_gray,
        generated_gray,
        data_range=255
    )

    return float(score), bbox



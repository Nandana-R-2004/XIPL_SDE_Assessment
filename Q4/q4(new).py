def identity_preservation_score(
    person_path,
    output_path
):
    """
    Calculate SSIM between the detected face in the
    original person image and the detected face in the
    Q3 try-on output.

    Score range:
        1.0 = extremely similar
        lower = greater structural change
    """

    original_face, original_bbox = extract_face_region(
        person_path
    )

    output_face, output_bbox = extract_face_region(
        output_path
    )

    if original_face is None:
        raise RuntimeError(
            f"Face not detected in original person: {person_path}"
        )

    if output_face is None:
        raise RuntimeError(
            f"Face not detected in Q3 output: {output_path}"
        )

    # Standardize both face crops
    FACE_SIZE = (256, 256)

    original_face = cv2.resize(
        original_face,
        FACE_SIZE,
        interpolation=cv2.INTER_AREA
    )

    output_face = cv2.resize(
        output_face,
        FACE_SIZE,
        interpolation=cv2.INTER_AREA
    )

    # Convert to grayscale for structural comparison
    original_gray = cv2.cvtColor(
        original_face,
        cv2.COLOR_RGB2GRAY
    )

    output_gray = cv2.cvtColor(
        output_face,
        cv2.COLOR_RGB2GRAY
    )

    score = ssim(
        original_gray,
        output_gray,
        data_range=255
    )

    return float(score), original_bbox, output_bbox



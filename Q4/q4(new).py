@torch.no_grad()
def clip_embedding(image):

    tensor = (
        clip_preprocess(image)
        .unsqueeze(0)
        .to(device)
    )

    features = clip_model.encode_image(
        tensor
    )

    return F.normalize(
        features.float(),
        dim=-1
    )


@torch.no_grad()
def garment_fidelity_score(
    garment_path,
    output_path,
    mask_path
):

    garment = Image.open(
        garment_path
    ).convert("RGB")

    output_garment = extract_garment_region(
        output_path,
        mask_path
    )

    garment_features = clip_embedding(
        garment
    )

    output_features = clip_embedding(
        output_garment
    )

    score = F.cosine_similarity(
        garment_features,
        output_features
    ).item()

    return float(score)



# Same parsing labels used in your previous Q3 cells
upper = (parsing == 4).astype(np.uint8)

left_arm = (parsing == 14).astype(np.uint8)
right_arm = (parsing == 15).astype(np.uint8)

arms = np.maximum(left_arm, right_arm)



print("=" * 70)

garment_analysis = {}


def analyze_garment_mask(mask_image):

    # --------------------------------------------------------
    # Binary mask
    # --------------------------------------------------------

    mask = np.array(
        mask_image.convert("L")
    )

    mask = (mask > 127).astype(np.uint8)

    # --------------------------------------------------------
    # Keep largest connected component
    # --------------------------------------------------------

    n, labels, stats, _ = cv2.connectedComponentsWithStats(
        mask,
        connectivity=8
    )

    if n <= 1:
        raise ValueError("Garment mask is empty.")

    largest = 1 + np.argmax(
        stats[1:, cv2.CC_STAT_AREA]
    )

    mask = (labels == largest).astype(np.uint8)

    # --------------------------------------------------------
    # Crop garment
    # --------------------------------------------------------

    ys, xs = np.where(mask > 0)

    x1 = xs.min()
    x2 = xs.max()

    y1 = ys.min()
    y2 = ys.max()

    crop = mask[
        y1:y2 + 1,
        x1:x2 + 1
    ]

    gh, gw = crop.shape

    # --------------------------------------------------------
    # Width at a relative row
    # --------------------------------------------------------

    def row_width(frac):

        y = min(
            gh - 1,
            max(0, int(frac * gh))
        )

        xx = np.where(
            crop[y] > 0
        )[0]

        if len(xx) == 0:
            return 0

        return int(
            xx.max() - xx.min() + 1
        )

    # --------------------------------------------------------
    # Estimate body width from lower-middle garment
    # --------------------------------------------------------

    body_width_values = []

    for frac in np.linspace(
        0.55,
        0.75,
        9
    ):

        w = row_width(frac)

        if w > 0:
            body_width_values.append(w)

    if body_width_values:
        body_width = float(
            np.median(body_width_values)
        )
    else:
        body_width = float(gw)

    body_width = max(
        body_width,
        1.0
    )

    # --------------------------------------------------------
    # Shoulder / upper widths
    # --------------------------------------------------------

    width20 = row_width(0.20)
    width30 = row_width(0.30)
    width40 = row_width(0.40)

    shoulder_ratio = max(
        width20,
        width30
    ) / body_width

    # --------------------------------------------------------
    # TOP AREA FRACTION
    #
    # Useful for detecting thin straps.
    # --------------------------------------------------------

    total_area = max(
        int(crop.sum()),
        1
    )

    top15_h = max(
        1,
        int(0.15 * gh)
    )

    top20_h = max(
        1,
        int(0.20 * gh)
    )

    top15_fraction = (
        crop[:top15_h].sum()
        / total_area
    )

    top20_fraction = (
        crop[:top20_h].sum()
        / total_area
    )

    # --------------------------------------------------------
    # ASPECT RATIO
    #
    # Long-sleeve tops are generally vertically much larger
    # than short-sleeve / strappy tops in these Q2 masks.
    # --------------------------------------------------------

    aspect_ratio = (
        gh / float(max(gw, 1))
    )

    # --------------------------------------------------------
    # CLASSIFICATION
    # --------------------------------------------------------

    # Thin straps:
    # extremely small amount of garment in top 15%.
    is_strappy = (
        top15_fraction < 0.05
    )

    # Long sleeve:
    # narrow shoulder profile + tall garment geometry.
    #
    # This distinguishes pair_02 from short sleeve garments.
    is_long_sleeve = (
        not is_strappy
        and shoulder_ratio < 1.15
        and aspect_ratio > 1.20
    )

    # Short sleeve:
    # substantial lateral width around shoulder area.
    is_short_sleeve = (
        not is_strappy
        and not is_long_sleeve
        and shoulder_ratio > 1.20
    )

    if is_strappy:

        garment_type = "STRAPPY"

    elif is_long_sleeve:

        garment_type = "LONG_SLEEVE"

    elif is_short_sleeve:

        garment_type = "SHORT_SLEEVE"

    else:

        garment_type = "SLEEVELESS"

    # --------------------------------------------------------
    # Return analysis
    # --------------------------------------------------------

    info = {

        "garment_type":
            garment_type,

        "top15_fraction":
            round(float(top15_fraction), 4),

        "top20_fraction":
            round(float(top20_fraction), 4),

        "body_width":
            round(float(body_width), 1),

        "shoulder_ratio":
            round(float(shoulder_ratio), 3),

        "aspect_ratio":
            round(float(aspect_ratio), 3),

        "width20":
            width20,

        "width30":
            width30,

        "width40":
            width40
    }

    return mask, crop, info



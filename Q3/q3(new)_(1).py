for i in range(1, 6):

    pair_id = f"pair_{i:02d}"

    # --------------------------------------------------------
    # Load person
    # --------------------------------------------------------

    person_path = os.path.join(
        PERSON_DIR,
        f"person_{i:02d}.png"
    )

    person = Image.open(
        person_path
    ).convert("RGB")

    W, H = person.size

    # --------------------------------------------------------
    # Load Q2 clothing mask
    # --------------------------------------------------------

    clothing_path = os.path.join(
        CLOTHING_MASK_DIR,
        f"person_{i:02d}.png"
    )

    clothing_img = Image.open(
        clothing_path
    ).convert("L")

    clothing_img = clothing_img.resize(
        (W, H),
        Image.Resampling.NEAREST
    )

    clothing = (
        np.array(clothing_img) > 127
    ).astype(np.uint8)

    clothing = clean_binary_mask(
        clothing
    )

    # --------------------------------------------------------
    # Load parsing map
    # --------------------------------------------------------

    parsing_path = os.path.join(
        PARSING_DIR,
        f"person_{i:02d}.png"
    )

    parsing_img = Image.open(
        parsing_path
    ).convert("L")

    parsing_img = parsing_img.resize(
        (W, H),
        Image.Resampling.NEAREST
    )

    parsing = np.array(
        parsing_img
    )

    # SCHP parsing:
    # label 14 = one arm
    # label 15 = other arm

    arm14 = (
        parsing == 14
    ).astype(np.uint8)

    arm15 = (
        parsing == 15
    ).astype(np.uint8)

    arms = np.maximum(
        arm14,
        arm15
    )

    # --------------------------------------------------------
    # Target garment type from Cell 5
    # --------------------------------------------------------

    garment_type = (
        garment_analysis[pair_id]
        ["info"]
        ["garment_type"]
    )

    # ========================================================
    # START WITH CURRENT CLOTHING REGION
    # ========================================================

    mask = clothing.copy()

    # ========================================================
    # SHORT SLEEVE
    # ========================================================

    if garment_type == "SHORT_SLEEVE":

        # Use only upper arm.
        #
        # Important:
        # We deliberately do NOT use the whole arm.

        upper14 = get_upper_arm(
            arm14,
            fraction=0.30
        )

        upper15 = get_upper_arm(
            arm15,
            fraction=0.30
        )

        upper_arms = np.maximum(
            upper14,
            upper15
        )

        # Small dilation gives CatVTON enough room
        # around the sleeve boundary.

        kernel_arm = cv2.getStructuringElement(
            cv2.MORPH_ELLIPSE,
            (9, 9)
        )

        upper_arms = cv2.dilate(
            upper_arms,
            kernel_arm,
            iterations=1
        )

        mask = np.maximum(
            mask,
            upper_arms
        )

    # ========================================================
    # LONG SLEEVE
    # ========================================================

    elif garment_type == "LONG_SLEEVE":

        # Long sleeve must allow CatVTON to replace
        # the complete visible arms.

        kernel_arm = cv2.getStructuringElement(
            cv2.MORPH_ELLIPSE,
            (9, 9)
        )

        full_arms = cv2.dilate(
            arms,
            kernel_arm,
            iterations=1
        )

        mask = np.maximum(
            mask,
            full_arms
        )

    # ========================================================
    # STRAPPY
    # ========================================================

    elif garment_type == "STRAPPY":

        # Current clothing region is sufficient.
        #
        # DO NOT add arms.
        # DO NOT manually create straps.
        # DO NOT copy garment geometry into person space.

        pass

    # ========================================================
    # SLEEVELESS
    # ========================================================

    elif garment_type == "SLEEVELESS":

        # Again, no arm expansion.

        pass

    # ========================================================
    # SMALL SAFE BORDER
    # ========================================================

    # Only a tiny dilation around the complete edit region.
    # This avoids leaving visible edges of the old garment.

    kernel_border = cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE,
        (5, 5)
    )

    mask = cv2.dilate(
        mask,
        kernel_border,
        iterations=1
    )

    # --------------------------------------------------------
    # Close tiny holes only

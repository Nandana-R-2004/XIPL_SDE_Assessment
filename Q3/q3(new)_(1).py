# 13. BOTTOM FIX
# ================================================================
# Same lesson from Pair 01:
# DO NOT give CatVTON unnecessary space below the original top.
# ================================================================

cloth_ys, cloth_xs = np.where(clothing > 0)

if len(cloth_ys) == 0:
    raise ValueError("Pair 02 clothing mask is empty.")


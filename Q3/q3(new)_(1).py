# Only cut the TORSO below the waist.
# Do not accidentally cut the long sleeves.

torso_width_zone = np.zeros(
    (H, W),
    dtype=np.uint8
)

torso_left = max(
    0,
    x1 - int(bw * 0.10)
)

torso_right = min(
    W - 1,
    x2 + int(bw * 0.10)
)

torso_width_zone[
    :,
    torso_left:torso_right + 1
] = 1


below_bottom = np.zeros(
    (H, W),
    dtype=np.uint8
)

if bottom_limit + 1 < H:
    below_bottom[
        bottom_limit + 1:,
        :
    ] = 1


remove_bottom = (
    torso_width_zone &
    below_bottom
)

mask[remove_bottom > 0] = 0


# ================================================================
# 14. RESTORE LONG SLEEVES
# ================================================================
# This is intentional.
# The torso bottom restriction must NOT delete sleeve pixels that
# naturally extend lower than the shirt hem.
# ================================================================

mask = np.maximum(
    mask,
    long_sleeves
)



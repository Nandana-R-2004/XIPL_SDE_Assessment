# ------------------------------------------------------------
# Helper: keep only components near the main clothing region
# ------------------------------------------------------------

def clean_binary_mask(mask):

    mask = (mask > 0).astype(np.uint8)

    n, labels, stats, _ = cv2.connectedComponentsWithStats(
        mask,
        connectivity=8
    )

    if n <= 1:
        return mask

    # Keep components larger than a small threshold.
    cleaned = np.zeros_like(mask)

    areas = stats[1:, cv2.CC_STAT_AREA]

    largest_area = areas.max()

    for idx in range(1, n):

        area = stats[idx, cv2.CC_STAT_AREA]

        if area >= max(
            20,
            int(largest_area * 0.002)
        ):
            cleaned[labels == idx] = 1

    return cleaned


# ------------------------------------------------------------
# Helper: upper part of arm only
# ------------------------------------------------------------

def get_upper_arm(arm_mask, fraction):

    arm = (arm_mask > 0).astype(np.uint8)

    ys, xs = np.where(arm > 0)

    if len(ys) == 0:
        return np.zeros_like(arm)

    top = ys.min()
    bottom = ys.max()

    height = max(
        bottom - top,
        1
    )

    cutoff = int(
        top + fraction * height
    )

    upper = arm.copy()

    upper[cutoff + 1:, :] = 0

    return upper



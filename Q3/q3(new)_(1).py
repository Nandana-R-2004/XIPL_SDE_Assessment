# 4. ORIGINAL UPPER-CLOTHING REGION
# ================================================================

base = np.maximum(clothing, upper)

ys, xs = np.where(base > 0)

if len(xs) == 0:
    raise ValueError("Pair 02 upper clothing region not found.")

x1 = int(xs.min())
x2 = int(xs.max())

y1 = int(ys.min())
y2 = int(ys.max())

bw = x2 - x1 + 1
bh = y2 - y1 + 1

cx = (x1 + x2) // 2

print()
print("Upper clothing bounds:")
print("x:", x1, "->", x2)
print("y:", y1, "->", y2)



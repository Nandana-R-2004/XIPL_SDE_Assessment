import os
import cv2
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image

print("=" * 65)
print("PAIR 04 — FIXING SHORT SLEEVES")
print("=" * 65)

BASE = "/content/drive/MyDrive/XIPL_SDE_Assessment"

person_path = f"{BASE}/Q1/person/person_04.png"
garment_path = f"{BASE}/Q1/garment/garment_04.jpg"
clothing_path = f"{BASE}/Q2/clothing_masks/person_04.png"

mask_path = (
    f"{BASE}/Q3/catvton_masks/"
    "pair_04_catvton_mask_final.png"
)

# ------------------------------------------------
# LOAD
# ------------------------------------------------

person = Image.open(person_path).convert("RGB")
garment = Image.open(garment_path).convert("RGB")

W, H = person.size

cloth = cv2.imread(clothing_path, cv2.IMREAD_GRAYSCALE)
cloth = cv2.resize(cloth, (W, H), interpolation=cv2.INTER_NEAREST)
cloth = (cloth > 127).astype(np.uint8)

# ------------------------------------------------
# FIND ORIGINAL TOP
# ------------------------------------------------

ys, xs = np.where(cloth > 0)

if len(xs) == 0:
    raise RuntimeError("Could not detect original clothing mask.")

x1, x2 = xs.min(), xs.max()
y1, y2 = ys.min(), ys.max()

cx = (x1 + x2) // 2

cloth_w = x2 - x1 + 1
cloth_h = y2 - y1 + 1

print(f"Original clothing bbox: x={x1}:{x2}, y={y1}:{y2}")

# ------------------------------------------------
# CREATE MASK
# ------------------------------------------------

mask = np.zeros((H, W), dtype=np.uint8)

# ================================================================
# 1. TORSO
# ================================================================

# Slight expansion around original crop top.
torso_left  = max(0, x1 - int(0.07 * cloth_w))
torso_right = min(W - 1, x2 + int(0.07 * cloth_w))

# Start around shoulder/top region.
top_y = max(0, y1 - int(0.08 * cloth_h))

# Extend below crop top enough for normal T-shirt,
# but NOT deep into the skirt.
bottom_y = min(
    H - 1,
    y2 + int(0.29 * cloth_h)
)

# Width changes gradually from shoulder to waist.
for y in range(top_y, bottom_y + 1):

    t = (y - top_y) / max(1, bottom_y - top_y)

    # slightly wider at shoulders, narrower lower torso
    extra = int((1.0 - t) * 0.035 * cloth_w)

    lx = max(0, torso_left - extra)
    rx = min(W - 1, torso_right + extra)

    mask[y, lx:rx + 1] = 255

# ================================================================
# 2. SHORT SLEEVES
# ================================================================

# Sleeves should cover the shoulder and upper-arm region,
# but stop well above the elbow.

shoulder_y = top_y + int(0.02 * cloth_h)

sleeve_bottom = min(
    H - 1,
    y1 + int(0.38 * cloth_h)
)

# Width outside original sleeveless top
sleeve_extension = int(0.28 * cloth_w)

left_outer = max(0, torso_left - sleeve_extension)
right_outer = min(W - 1, torso_right + sleeve_extension)

# Polygon gives natural downward-sloping sleeves.

left_sleeve = np.array([
    [torso_left + int(0.04 * cloth_w), shoulder_y],
    [left_outer + int(0.07 * cloth_w), shoulder_y + int(0.08 * cloth_h)],
    [left_outer, sleeve_bottom - int(0.06 * cloth_h)],
    [torso_left, sleeve_bottom],
    [torso_left + int(0.03 * cloth_w), shoulder_y + int(0.18 * cloth_h)]
], dtype=np.int32)

right_sleeve = np.array([
    [torso_right - int(0.04 * cloth_w), shoulder_y],
    [right_outer - int(0.07 * cloth_w), shoulder_y + int(0.08 * cloth_h)],
    [right_outer, sleeve_bottom - int(0.06 * cloth_h)],
    [torso_right, sleeve_bottom],
    [torso_right - int(0.03 * cloth_w), shoulder_y + int(0.18 * cloth_h)]
], dtype=np.int32)

cv2.fillPoly(mask, [left_sleeve], 255)
cv2.fillPoly(mask, [right_sleeve], 255)

# ================================================================
# 3. KEEP ORIGINAL TOP FULLY INCLUDED
# ================================================================

mask[cloth > 0] = 255

# ================================================================
# 4. CLEAN SHAPE
# ================================================================

kernel = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE,
    (9, 9)
)

mask = cv2.morphologyEx(
    mask,
    cv2.MORPH_CLOSE,
    kernel
)

# ------------------------------------------------
# KEEP ONLY MAIN CONNECTED COMPONENT
# ------------------------------------------------

num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(
    (mask > 0).astype(np.uint8),
    connectivity=8
)

if num_labels > 1:

    largest = 1 + np.argmax(
        stats[1:, cv2.CC_STAT_AREA]
    )

    mask = np.where(
        labels == largest,
        255,
        0
    ).astype(np.uint8)

# ================================================================
# 5. ROUND THE NECK AREA
# ================================================================

# Allow CatVTON to reconstruct the crew neckline,
# while avoiding excessive masking toward the neck/head.

neck_center_x = cx
neck_center_y = top_y + int(0.03 * cloth_h)

neck_rx = int(0.18 * cloth_w)
neck_ry = int(0.10 * cloth_h)

cv2.ellipse(
    mask,
    (neck_center_x, neck_center_y),
    (neck_rx, neck_ry),
    0,
    0,
    360,
    0,
    -1
)

# ================================================================
# SAVE
# ================================================================

Image.fromarray(mask).save(mask_path)

print()
print("Saved:")
print(mask_path)


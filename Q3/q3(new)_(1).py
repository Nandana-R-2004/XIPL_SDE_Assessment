import os
import cv2
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image

# ================================================================
# 1. PATHS
# ================================================================

BASE = "/content/drive/MyDrive/XIPL_SDE_Assessment"

person_path = f"{BASE}/Q1/person/person_01.png"
garment_path = f"{BASE}/Q1/garment/garment_01.jpg"

# Your ORIGINAL Q2 clothing mask
clothing_path = f"{BASE}/Q2/clothing_masks/person_01.png"

# Q2 parsing map
parsing_path = f"{BASE}/Q2/parsing_maps/person_01.png"

out_dir = f"{BASE}/Q3/catvton_masks"
os.makedirs(out_dir, exist_ok=True)

out_path = f"{out_dir}/pair_01_catvton_mask_final.png"


# ================================================================
# 2. LOAD PERSON + GARMENT
# ================================================================

person = Image.open(person_path).convert("RGB")
garment = Image.open(garment_path).convert("RGB")

W, H = person.size

print("Person size:", (W, H))


# ================================================================
# 3. LOAD ORIGINAL CLOTHING MASK
# ================================================================

clothing = Image.open(clothing_path).convert("L")
clothing = clothing.resize((W, H), Image.Resampling.NEAREST)

clothing = np.array(clothing)
clothing = (clothing > 127).astype(np.uint8)


# ================================================================
# 4. LOAD HUMAN PARSING
# ================================================================

parsing = Image.open(parsing_path).convert("L")
parsing = parsing.resize((W, H), Image.Resampling.NEAREST)
parsing = np.array(parsing)


# ================================================================
# 5. PARSING REGIONS
# ================================================================

# ATR-style labels used in your previous cells
upper = (parsing == 4).astype(np.uint8)

arm_l = (parsing == 14).astype(np.uint8)
arm_r = (parsing == 15).astype(np.uint8)

arms = np.maximum(arm_l, arm_r)


# ================================================================
# 6. ORIGINAL TOP REGION
# ================================================================

base = np.maximum(clothing, upper)

ys, xs = np.where(base > 0)

if len(xs) == 0:
    raise ValueError("Could not find original upper-clothing region.")

x1 = int(xs.min())
x2 = int(xs.max())
y1 = int(ys.min())
y2 = int(ys.max())

bw = x2 - x1 + 1
bh = y2 - y1 + 1
cx = (x1 + x2) // 2

print("Original top bounds:")
print("x:", x1, "->", x2)
print("y:", y1, "->", y2)


# ================================================================
# 7. CLEAN + SLIGHTLY EXPAND ORIGINAL TORSO
# ================================================================

kernel_close = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE, (13, 13)
)

torso = cv2.morphologyEx(
    base,
    cv2.MORPH_CLOSE,
    kernel_close
)

kernel_expand = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE, (9, 9)
)

torso = cv2.dilate(
    torso,
    kernel_expand,
    iterations=1
)


# ================================================================
# 8. SHORT-SLEEVE REGION
# ================================================================

# Only use upper-arm area.
# Do NOT let the mask run down the full arms.

arm_zone = arms.copy()

max_sleeve_y = min(
    H - 1,
    y1 + int(bh * 0.43)
)

# Correct row-based cropping
arm_zone[max_sleeve_y + 1:, :] = 0


# Restrict arm mask horizontally around torso
arm_limit = np.zeros((H, W), dtype=np.uint8)

extra_x = int(bw * 0.32)

left = max(0, x1 - extra_x)
right = min(W - 1, x2 + extra_x)

top = max(0, y1 - int(bh * 0.08))
bottom = max_sleeve_y

cv2.rectangle(
    arm_limit,
    (left, top),
    (right, bottom),
    1,
    -1
)

arm_zone = arm_zone & arm_limit


# Expand upper arms slightly to give CatVTON sleeve-generation room
sleeve_kernel = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE, (25, 25)
)

sleeves = cv2.dilate(
    arm_zone,
    sleeve_kernel,
    iterations=1
)

sleeves = sleeves & arm_limit


# ================================================================
# 9. SHOULDER BRIDGE
# ================================================================

# This lets CatVTON replace the tank-top straps with T-shirt shoulders.

shoulders = np.zeros((H, W), dtype=np.uint8)

shoulder_top = max(
    0,
    y1 - int(bh * 0.05)
)

shoulder_bottom = min(
    H - 1,
    y1 + int(bh * 0.22)
)

shoulder_x1 = max(
    0,
    x1 - int(bw * 0.10)
)

shoulder_x2 = min(
    W - 1,
    x2 + int(bw * 0.10)
)

cv2.rectangle(
    shoulders,
    (shoulder_x1, shoulder_top),
    (shoulder_x2, shoulder_bottom),
    1,
    -1
)


# ================================================================
# 10. COMBINE TORSO + SHOULDERS + SHORT SLEEVES
# ================================================================

mask = torso.copy()
mask = np.maximum(mask, shoulders)
mask = np.maximum(mask, sleeves)


# ================================================================
# 11. CREW-NECK PROTECTION
# ================================================================

# Keep neck/head OUTSIDE the inpainting region.
# This creates the crew-neck opening.

neck_hole = np.zeros((H, W), dtype=np.uint8)

neck_rx = max(
    12,
    int(bw * 0.21)
)

neck_ry = max(
    12,
    int(bh * 0.12)
)

neck_cx = cx

neck_cy = max(
    y1,
    int(y1 + bh * 0.02)
)

cv2.ellipse(
    neck_hole,
    (neck_cx, neck_cy),
    (neck_rx, neck_ry),
    0,
    0,
    360,
    1,
    -1
)

mask[neck_hole > 0] = 0


# ================================================================
# 12. IMPORTANT BOTTOM FIX
# ================================================================
# The previous result was good except CatVTON generated extra
# shirt below the intended bottom.
#
# So DO NOT extend the mask downward.
#
# Use the ORIGINAL clothing mask to estimate the bottom edge.
# Add only a very small allowance for natural replacement.
# ================================================================

cloth_ys, cloth_xs = np.where(clothing > 0)

if len(cloth_ys) == 0:
    raise ValueError("Original clothing mask is empty.")

original_bottom = int(cloth_ys.max())

# Tiny allowance only.
# Increase from 0.015 -> 0.02 ONLY if necessary.
bottom_allowance = max(2, int(bh * 0.015))

bottom_limit = min(
    H - 1,
    original_bottom + bottom_allowance
)

print("Original clothing bottom:", original_bottom)
print("Final CatVTON bottom limit:", bottom_limit)

# HARD CUT:
# absolutely no mask below this line
mask[bottom_limit + 1:, :] = 0


# ================================================================
# 13. CLEAN FINAL MASK
# ================================================================

final_kernel = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE, (7, 7)
)

mask = cv2.morphologyEx(
    mask,
    cv2.MORPH_CLOSE,
    final_kernel
)


# Re-apply bottom restriction after morphology.
# This is important because closing can add pixels below the cutoff.
mask[bottom_limit + 1:, :] = 0


# ================================================================
# 14. KEEP MAIN CONNECTED COMPONENT
# ================================================================

num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(
    mask.astype(np.uint8),
    connectivity=8
)

if num_labels > 1:

    largest = 1 + np.argmax(
        stats[1:, cv2.CC_STAT_AREA]
    )

    mask = (
        labels == largest
    ).astype(np.uint8)


# ================================================================
# 15. FINAL BINARY MASK
# ================================================================

final_mask = (mask * 255).astype(np.uint8)

Image.fromarray(final_mask).save(out_path)


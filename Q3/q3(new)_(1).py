# 5. CLEAN TORSO
# ================================================================

close_kernel = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE,
    (13, 13)
)

torso = cv2.morphologyEx(
    base,
    cv2.MORPH_CLOSE,
    close_kernel
)


# Slight expansion around clothing boundary
expand_kernel = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE,
    (9, 9)
)

torso = cv2.dilate(
    torso,
    expand_kernel,
    iterations=1
)


# ================================================================
# 6. LONG-SLEEVE ARM REGION
# ================================================================
# Pair 02 is different from Pair 01:
#
# Pair 01 -> only upper arms
# Pair 02 -> nearly the entire visible arms
#
# Parsing already gives us the actual arm locations.
# ================================================================

arm_zone = arms.copy()


# ================================================================
# 7. PROTECT VERY BOTTOM OF ARMS / HAND AREA
# ================================================================
# We don't want unnecessary inpainting far beyond the arm region.
# Find the real parsed-arm vertical extent.
# ================================================================

arm_ys, arm_xs = np.where(arm_zone > 0)

if len(arm_ys) == 0:
    raise ValueError("Pair 02 arm regions were not detected.")

arm_top = int(arm_ys.min())
arm_bottom = int(arm_ys.max())

print()
print("Parsed arm range:")
print("y:", arm_top, "->", arm_bottom)


# Small upward/downward freedom
arm_top_limit = max(
    0,
    arm_top - 8
)

# Keep almost entire arm but avoid expanding below it
arm_bottom_limit = min(
    H - 1,
    arm_bottom + 3
)


# ================================================================
# 8. DILATE ARMS FOR LONG-SLEEVE FABRIC
# ================================================================
# CatVTON needs some space around the bare arm so it can synthesize
# fabric rather than simply recolouring the skin.
# ================================================================

arm_kernel = cv2.getStructuringElement(
    cv2.MORPH_ELLIPSE,
    (19, 19)
)

long_sleeves = cv2.dilate(
    arm_zone,
    arm_kernel,
    iterations=1
)


# Restrict vertical range
long_sleeves[:arm_top_limit, :] = 0
long_sleeves[arm_bottom_limit + 1:, :] = 0


# ================================================================
# 9. RESTRICT ARM EXPANSION HORIZONTALLY
# ================================================================

arm_x_margin = int(bw * 0.42)

arm_boundary = np.zeros(
    (H, W),
    dtype=np.uint8
)

left_limit = max(
    0,
    x1 - arm_x_margin
)

right_limit = min(
    W - 1,
    x2 + arm_x_margin
)

cv2.rectangle(
    arm_boundary,
    (left_limit, arm_top_limit),
    (right_limit, arm_bottom_limit),
    1,
    -1
)

long_sleeves = long_sleeves & arm_boundary


# ================================================================
# 10. SHOULDER CONNECTION
# ================================================================
# Connect torso and arms so the final mask is one continuous
# garment-shaped region.
# ================================================================

shoulders = np.zeros(
    (H, W),
    dtype=np.uint8
)

shoulder_top = max(
    0,
    y1 - int(bh * 0.05)
)

shoulder_bottom = min(
    H - 1,
    y1 + int(bh * 0.28)
)

shoulder_left = max(
    0,
    x1 - int(bw * 0.12)
)

shoulder_right = min(
    W - 1,
    x2 + int(bw * 0.12)
)

cv2.rectangle(
    shoulders,
    (shoulder_left, shoulder_top),
    (shoulder_right, shoulder_bottom),
    1,
    -1
)


